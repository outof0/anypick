import { join } from 'node:path';
import { ensureDir, pathExists, removePath, writeTextFile } from '../utils/fs';
import { clientDir, clientEnvPath, clientEnvPs1Path } from '../core/paths';
import { HotplugError } from '../utils/errors';

/**
 * Write portable env files for a client under ~/.hotplug/clients/<id>/.
 * Always written so users can `source` them; adapters may also write native config.
 */
export async function writeClientEnvFiles(
  hotplugRoot: string,
  clientId: string,
  env: Record<string, string>,
): Promise<string[]> {
  for (const key of Object.keys(env)) {
    // These names are emitted into executable shell and PowerShell files.
    // Profile overlay keys are user/config supplied, so never let one become
    // syntax (for example `X; Invoke-Expression ...`).
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) {
      throw new HotplugError(`Invalid environment variable name: ${JSON.stringify(key)}.`, {
        code: 'CLIENT_CONFIG_INVALID',
      });
    }
  }
  await ensureDir(clientDir(hotplugRoot, clientId));
  const shPath = clientEnvPath(hotplugRoot, clientId);
  const ps1Path = clientEnvPs1Path(hotplugRoot, clientId);

  const shLines = [
    `# Generated by hotplug — do not edit by hand`,
    `# source ${shPath}`,
    ...Object.entries(env).map(([k, v]) => `export ${k}=${shellQuote(v)}`),
    '',
  ];
  const ps1Lines = [
    `# Generated by hotplug — do not edit by hand`,
    ...Object.entries(env).map(([k, v]) => `$env:${k} = ${psQuote(v)}`),
    '',
  ];

  await writeTextFile(shPath, shLines.join('\n'), 0o600);
  await writeTextFile(ps1Path, ps1Lines.join('\n'), 0o600);
  return [shPath, ps1Path];
}

export async function removeClientEnvFiles(hotplugRoot: string, clientId: string): Promise<void> {
  for (const path of [
    clientEnvPath(hotplugRoot, clientId),
    clientEnvPs1Path(hotplugRoot, clientId),
  ]) {
    if (await pathExists(path)) {
      await removePath(path);
    }
  }
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function psQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Marker used in JSON settings to track hotplug-managed env keys. */
export const HOTPLUG_MANAGED_KEY = '_hotplugManaged';

export function managedMarker(keys: string[]): {
  keys: string[];
  updatedAt: string;
} {
  return { keys, updatedAt: new Date().toISOString() };
}

export function clientHomeConfigDir(clientId: string, home: string): string {
  return join(home, `.${clientId === 'claude' ? 'claude' : clientId}`);
}
