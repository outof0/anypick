// Package docsync renders documentation that must match the built-in
// registries, so the README cannot drift from the code that ships.
package docsync

import (
	"fmt"
	"sort"
	"strings"

	"github.com/outof0/anypick/go/internal/client"
	"github.com/outof0/anypick/go/internal/provider"
)

// Block is one generated region of README.md, delimited by HTML comments.
type Block string

const (
	// Summary is the one-line count on README's first screen.
	Summary Block = "supported-summary"
	// Table is the full list of apps and sources further down.
	Table Block = "supported"
)

// Start is the opening marker of the block.
func (b Block) Start() string {
	return fmt.Sprintf("<!-- %s:start (generated by `make readme-supported`; do not edit) -->", b)
}

// End is the closing marker of the block.
func (b Block) End() string { return fmt.Sprintf("<!-- %s:end -->", b) }

// featuredApps are named in the first-screen summary, in this order. Each must
// stay registered: the summary test fails if one is removed.
var featuredApps = []string{"claude", "codex", "gemini", "opencode"}

type source struct {
	name, how, id string
	login         bool
	// keyless sources take no key at all: every credential product they
	// publish is key-optional (a local model server).
	keyless bool
}

// Supported is what the registries ship: coding apps and account sources.
type Supported struct {
	apps    []string // "Name (`id`)", registry order
	byID    map[string]string
	sources []source // login-capable first, then by name
}

// Load builds the registries the app composes at startup. home is only used
// to construct the adapters; nothing is read from it.
func Load(home string) (Supported, error) {
	var s Supported
	clients := client.NewRegistry()
	if err := client.RegisterBuiltin(clients, home, home); err != nil {
		return s, err
	}
	native := provider.NewRegistry()
	if err := provider.RegisterBuiltin(native, home); err != nil {
		return s, err
	}
	compatibles := provider.NewRegistry()
	if err := provider.RegisterBuiltinCompatibles(compatibles, home); err != nil {
		return s, err
	}
	s.byID = map[string]string{}
	for _, id := range clients.IDs() {
		c, err := clients.Get(id)
		if err != nil {
			return s, err
		}
		s.byID[id] = c.Name()
		s.apps = append(s.apps, fmt.Sprintf("%s (`%s`)", c.Name(), id))
	}
	seen := map[string]bool{}
	for _, reg := range []*provider.Registry{native, compatibles} {
		for _, id := range reg.IDs() {
			if seen[id] {
				continue
			}
			seen[id] = true
			p, err := reg.Get(id)
			if err != nil {
				return s, err
			}
			how, login := connectWith(p)
			s.sources = append(s.sources, source{p.Name(), how, id, login, keylessSource(p)})
		}
	}
	sort.SliceStable(s.sources, func(i, j int) bool {
		if s.sources[i].login != s.sources[j].login {
			return s.sources[i].login
		}
		return strings.ToLower(s.sources[i].name) < strings.ToLower(s.sources[j].name)
	})
	return s, nil
}

// SummaryLine is the first-screen count, naming the featured apps.
func (s Supported) SummaryLine() (string, error) {
	var names []string
	for _, id := range featuredApps {
		name, ok := s.byID[id]
		if !ok {
			return "", fmt.Errorf("featured app %q is not registered; update featuredApps", id)
		}
		names = append(names, name)
	}
	logins, keyless := 0, 0
	for _, src := range s.sources {
		switch {
		case src.login:
			logins++
		case src.keyless:
			keyless++
		}
	}
	// "The rest by API key" would be false for a server that takes none.
	servers := ""
	if keyless > 0 {
		servers = fmt.Sprintf(", %d local model servers that need no key", keyless)
	}
	return fmt.Sprintf("Works with **%d coding apps** (%s and %d more) and **%d sources**: "+
		"%d you sign in to or reuse an existing login for%s, the rest by API key. "+
		"[Full list](#supported).\n",
		len(s.apps), strings.Join(names, ", "), len(s.apps)-len(names),
		len(s.sources), logins, servers), nil
}

// keylessSource reports a source whose every credential product is
// key-optional.
func keylessSource(p provider.Provider) bool {
	defs, ok := p.(provider.CredentialDefinitionsProvider)
	if !ok {
		return false
	}
	list := defs.CredentialDefinitions()
	if len(list) == 0 {
		return false
	}
	for _, d := range list {
		if !d.SecretOptional {
			return false
		}
	}
	return true
}

// TableMarkdown is the full list of coding apps and sources.
func (s Supported) TableMarkdown() string {
	var b strings.Builder
	b.WriteString("**Coding apps** AnyPick can point at a saved source:\n\n")
	b.WriteString(strings.Join(s.apps, " · "))
	b.WriteString("\n\n| Source | Connect with | ID |\n| --- | --- | --- |\n")
	for _, r := range s.sources {
		fmt.Fprintf(&b, "| %s | %s | `%s` |\n", r.name, r.how, r.id)
	}
	return b.String()
}

// connectWith describes how an account is added, from the capabilities the
// provider declares: a browser sign-in, a native login AnyPick can save, and
// the credential kinds it accepts.
func connectWith(p provider.Provider) (string, bool) {
	var parts []string
	_, signIn := p.(provider.LoginMethodsProvider)
	defs, hasDefs := p.(provider.CredentialDefinitionsProvider)
	login := signIn || !hasDefs
	switch {
	case signIn:
		parts = append(parts, "Sign in, or save your existing login")
	case login:
		parts = append(parts, "Save your existing login")
	}
	if hasDefs {
		var labels []string
		for _, d := range defs.CredentialDefinitions() {
			labels = append(labels, d.Label)
		}
		if len(labels) > 0 {
			parts = append(parts, strings.Join(labels, " or "))
		}
	}
	return strings.Join(parts, "; "), login
}

// Replace swaps the text between the block's markers in doc.
func (b Block) Replace(doc, body string) (string, error) {
	start := strings.Index(doc, b.Start())
	end := strings.Index(doc, b.End())
	if start < 0 || end < start {
		return "", fmt.Errorf("README.md has no %q ... %q block", b.Start(), b.End())
	}
	return doc[:start+len(b.Start())] + "\n\n" + body + "\n" + doc[end:], nil
}
